#!/usr/bin/env bash
# Regenerates CHANGELOG.md: for every release tag, the main commits since the previous tag of the same
# product that touched that product's folder (manifest bookkeeping commits are left out).
# Tags: <Folder>-v<version> (plugins/<Folder>) and app-<Name>-v<version> (apps/<Name>).
# Usage: scripts/changelog.sh   (run from anywhere; rewrites CHANGELOG.md at the repo root)
set -euo pipefail
cd "$(git rev-parse --show-toplevel)"
out=CHANGELOG.md

path_of() { case "$1" in app-*) echo "apps/${1#app-}";; *) echo "plugins/$1";; esac; }
product_of() { local t="$1"; echo "${t%-v*}"; }

{
  echo "# Changelog"
  echo
  echo "Generated by \`scripts/changelog.sh\` from git history: commits on main since the previous release of the same product that touched its folder."
  echo "Regenerate after tagging a release."

  products=$(git tag | sed 's/-v[0-9].*$//' | sort -u)
  for prod in $products; do
    dir=$(path_of "$prod")
    [ -d "$dir" ] || continue
    echo
    echo "## $prod"
    tags=$(git tag --list "${prod}-v*" | sort -t v -k2 -V | tac)
    prev_of_newest=""
    # unreleased
    newest=$(echo "$tags" | head -1)
    unrel=$(git log --no-merges --format='- %s (%h)' "$newest..HEAD" -- "$dir" | grep -v '^- manifest:' || true)
    if [ -n "$unrel" ]; then echo; echo "### Unreleased"; echo; echo "$unrel"; fi
    arr=($tags)
    for i in "${!arr[@]}"; do
      t="${arr[$i]}"
      older="${arr[$((i+1))]:-}"
      ver="${t##*-v}"
      date=$(git log -1 --format=%as "$t")
      range="$t"; [ -n "$older" ] && range="$older..$t"
      echo
      echo "### $ver ($date)"
      echo
      lines=$(git log --no-merges --format='- %s (%h)' "$range" -- "$dir" | grep -v '^- manifest:' || true)
      if [ -n "$lines" ]; then echo "$lines"; else echo "- (no changes under \`$dir\`)"; fi
    done
  done
} > "$out"
echo "wrote $out"
